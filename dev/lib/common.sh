# Exit status for "this suite or command can't work yet". `dev/run test all` tells it apart
# from a failure in its summary; both make the run fail.
EXIT_NOT_AVAILABLE=3

# ---- Output ------------------------------------------------------------------------------

log_step() {
  printf '\n==> %s\n' "$*" >&2
}

log_info() {
  printf '    %s\n' "$*" >&2
}

log_warn() {
  printf 'warning: %s\n' "$*" >&2
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

# Why: suites whose files don't exist yet must say so clearly and fail, never pass silently.
not_available() {
  printf 'not available yet: %s\n' "$*" >&2
  exit "$EXIT_NOT_AVAILABLE"
}

require_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    die "Docker is required (plan §5). Install Docker with the compose plugin."
  fi
  if ! docker compose version >/dev/null 2>&1; then
    die "The Docker compose plugin is required ('docker compose version' failed)."
  fi
}

is_ci() {
  [ "${CI:-false}" = "true" ]
}
