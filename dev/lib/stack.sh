# shellcheck shell=bash
# Stack state and the docker compose wrapper.
#
# Why: every compose call must see the same project name, ports, credentials and override
# files, or compose would recreate containers or fail on unset variables. prepare_stack sets
# all of them for one mode; compose, wpcli and runner_compose then use them.

KNOWN_MODES="dev test"

validate_mode() {
  local mode="$1"
  case "$mode" in
    dev | test)
      return 0
      ;;
    *)
      die "Unknown mode '$mode'. Use 'dev' or 'test'."
      ;;
  esac
}

mode_state_dir() {
  local mode="$1"
  printf '%s/%s' "$STATE_ROOT" "$mode"
}

mode_state_file() {
  local mode="$1"
  printf '%s/stack.env' "$(mode_state_dir "$mode")"
}

# The mode that seed, reset, variant and logs act on: WPU_MODE, else the last `up`, else dev.
active_mode() {
  local recorded_mode_file="$STATE_ROOT/active-mode"
  if [ -n "${WPU_MODE:-}" ]; then
    echo "$WPU_MODE"
  elif [ -s "$recorded_mode_file" ]; then
    cat "$recorded_mode_file"
  else
    echo "dev"
  fi
}

remember_active_mode() {
  local mode="$1"
  mkdir -p "$STATE_ROOT"
  echo "$mode" > "$STATE_ROOT/active-mode"
}

git_common_dir() {
  local common_dir=""
  if command -v git >/dev/null 2>&1; then
    common_dir="$(git -C "$REPO_ROOT" rev-parse --path-format=absolute --git-common-dir 2>/dev/null || true)"
  fi
  if [ -z "$common_dir" ] || [ ! -d "$common_dir" ]; then
    # No git repository: mount an empty placeholder instead of letting Docker create a
    # root-owned directory somewhere.
    common_dir="$STATE_ROOT/no-git"
    mkdir -p "$common_dir"
  fi
  printf '%s' "$common_dir"
}

# Reads the recorded state of a mode (ports, app password) into STATE_* variables.
load_mode_state() {
  local mode="$1"
  local state_file
  state_file="$(mode_state_file "$mode")"

  STATE_PORT_BLOCK=""
  STATE_APP_PASSWORD=""
  if [ ! -f "$state_file" ]; then
    return 0
  fi
  # shellcheck disable=SC1090
  source "$state_file"
  # State recorded for another identity (a copied checkout, or WPU_WORKTREE_PATH set) belongs
  # to a different stack; ignore it.
  if [ "${COMPOSE_PROJECT_NAME:-}" != "$(project_name_for_mode "$mode")" ]; then
    return 0
  fi
  STATE_PORT_BLOCK="${WPU_PORT_BLOCK:-}"
  STATE_APP_PASSWORD="${WPU_APP_PASSWORD:-}"
}

# Writes the state file. Values never contain single quotes, so plain single quoting keeps the
# file valid for bash `source`, Node's --env-file and dotenv alike.
save_mode_state() {
  local mode="$1"
  local state_dir
  state_dir="$(mode_state_dir "$mode")"
  mkdir -p "$state_dir"
  {
    echo "# Generated by dev/run. Do not edit."
    echo "WPU_MODE='$WPU_MODE'"
    echo "COMPOSE_PROJECT_NAME='$COMPOSE_PROJECT_NAME'"
    echo "WPU_PORT_BLOCK='$WPU_PORT_BLOCK'"
    echo "WPU_SITE_URL='$WPU_SITE_URL'"
    echo "WPU_APP_USER='$WPU_APP_USER'"
    echo "WPU_APP_PASSWORD='$WPU_APP_PASSWORD'"
  } > "$(mode_state_file "$mode")"
  chmod 600 "$(mode_state_file "$mode")"
}

# The env file the host server and Vite read in `dev` mode (plan §5.1). Only written for dev.
write_env_wp_file() {
  local wordpress_url="http://localhost:$WPU_PORT_WORDPRESS"
  {
    echo "# Generated by 'dev/run up dev' for this worktree. Do not edit; do not commit."
    echo "# The host server (npm run dev) and Vite read it; see docs/media-manager/tracks/D-handoff.md."
    echo "WP_URL='$wordpress_url'"
    echo "WP_USERNAME='$WPU_APP_USER'"
    echo "WP_APP_PASSWORD='$WPU_APP_PASSWORD'"
    echo "AUTH_USERNAME='$LOGIN_USER'"
    echo "AUTH_PASSWORD='$LOGIN_PASSWORD'"
    echo "PORT='$WPU_PORT_SERVER'"
    echo "WPU_VITE_PORT='$WPU_PORT_VITE'"
    echo "WPU_API_TARGET='http://localhost:$WPU_PORT_SERVER'"
    echo "WPU_WP_ADMIN_URL='$wordpress_url/wp-admin/'"
    echo "WPU_ADMIN_USER='$ADMIN_USER'"
    echo "WPU_ADMIN_PASSWORD='$ADMIN_PASSWORD'"
  } > "$ENV_WP_FILE"
  chmod 600 "$ENV_WP_FILE"
}

build_compose_file_args() {
  local mode="$1"
  COMPOSE_FILE_ARGS=(--file "$DEV_DIR/compose.yml")
  if [ "$mode" = "dev" ]; then
    COMPOSE_FILE_ARGS+=(--file "$DEV_DIR/compose.dev.yml")
    if [ -d "$PLUGIN_SOURCE_DIR" ]; then
      COMPOSE_FILE_ARGS+=(--file "$DEV_DIR/compose.plugin-source.yml")
    fi
  else
    COMPOSE_FILE_ARGS+=(--file "$DEV_DIR/compose.test.yml")
    if [ -d "$PLUGIN_DIST_DIR" ]; then
      COMPOSE_FILE_ARGS+=(--file "$DEV_DIR/compose.plugin-dist.yml")
    fi
    if is_ci; then
      COMPOSE_FILE_ARGS+=(--file "$DEV_DIR/compose.ci.yml")
    fi
  fi
}

# Bind-mount sources must exist before compose runs, or Docker creates them as root.
ensure_host_directories() {
  local mode="$1"
  mkdir -p \
    "$(mode_state_dir "$mode")/ca" \
    "$CACHE_DIR/downloads" \
    "$CACHE_DIR/npm" \
    "$MOCK_BUILD_DIR" \
    "$RESULTS_DIR"
}

# Sets and exports everything compose needs for one mode.
#   choose_ports=true   pick (and check) a free port block; only `up` does this
#   choose_ports=false  use the recorded block, or the preferred one when nothing is recorded
prepare_stack() {
  local mode="$1"
  local choose_ports="${2:-false}"
  validate_mode "$mode"
  load_mode_state "$mode"

  export WPU_MODE="$mode"
  export COMPOSE_PROJECT_NAME
  COMPOSE_PROJECT_NAME="$(project_name_for_mode "$mode")"

  if [ "$choose_ports" = "true" ]; then
    WPU_PORT_BLOCK="$(choose_port_block "$mode" "$STATE_PORT_BLOCK" "$COMPOSE_PROJECT_NAME")"
  elif [ -n "$STATE_PORT_BLOCK" ]; then
    WPU_PORT_BLOCK="$STATE_PORT_BLOCK"
  else
    WPU_PORT_BLOCK="$(port_block_start "$(preferred_port_block_index)")"
  fi
  export WPU_PORT_BLOCK
  export WPU_PORT_WORDPRESS=$(( WPU_PORT_BLOCK + PORT_OFFSET_DEV_WORDPRESS ))
  export WPU_PORT_SERVER=$(( WPU_PORT_BLOCK + PORT_OFFSET_DEV_SERVER ))
  export WPU_PORT_VITE=$(( WPU_PORT_BLOCK + PORT_OFFSET_DEV_VITE ))
  export WPU_PORT_PROXY=$(( WPU_PORT_BLOCK + PORT_OFFSET_TEST_PROXY ))
  export WPU_BIND_ADDRESS="${WPU_BIND_ADDRESS:-127.0.0.1}"

  if [ "$mode" = "dev" ]; then
    export WPU_SITE_URL="http://localhost:$WPU_PORT_WORDPRESS"
  else
    export WPU_SITE_URL="https://wp.wpu.test"
  fi

  export WPU_STATE_DIR
  WPU_STATE_DIR="$(mode_state_dir "$mode")"
  export WPU_REPO_ROOT="$REPO_ROOT"
  export WPU_GIT_COMMON_DIR
  WPU_GIT_COMMON_DIR="$(git_common_dir)"
  export WPU_UID
  WPU_UID="$(id -u)"
  export WPU_GID
  WPU_GID="$(id -g)"
  export WPU_PLAYWRIGHT_VERSION="$PLAYWRIGHT_VERSION"
  export WPU_PLAYWRIGHT_IMAGE="$PLAYWRIGHT_IMAGE"
  export WPU_NODE_IMAGE="$NODE_IMAGE"

  export WPU_APP_USER="$APP_USER_LOGIN"
  export WPU_APP_PASSWORD="$STATE_APP_PASSWORD"
  export WPU_ADMIN_USER="$ADMIN_USER"
  export WPU_ADMIN_PASSWORD="$ADMIN_PASSWORD"
  export WPU_LOGIN_USER="$LOGIN_USER"
  export WPU_LOGIN_PASSWORD="$LOGIN_PASSWORD"
  export WPU_SESSION_SECRET="$SESSION_SECRET"

  build_compose_file_args "$mode"
  ensure_host_directories "$mode"
}

compose() {
  docker compose \
    --project-name "$COMPOSE_PROJECT_NAME" \
    --project-directory "$DEV_DIR" \
    "${COMPOSE_FILE_ARGS[@]}" \
    "$@"
}

# A one-off container of a service, without compose's progress lines (they would bury the
# output people care about) and without starting dependencies.
compose_run() {
  docker compose \
    --progress quiet \
    --project-name "$COMPOSE_PROJECT_NAME" \
    --project-directory "$DEV_DIR" \
    "${COMPOSE_FILE_ARGS[@]}" \
    run --rm --no-deps -T \
    "$@"
}

# wp-cli in a one-off container next to the running WordPress. Always names `wp` explicitly:
# the image's entrypoint guesses wrongly while WordPress isn't installed yet.
wpcli() {
  compose_run wpcli wp "$@"
}

# A shell inside the one-off wp-cli container (for snapshots and downloads).
wpcli_shell() {
  local script="$1"
  shift
  compose_run wpcli sh -c "$script" sh "$@"
}

stack_is_running() {
  project_has_running_containers "$COMPOSE_PROJECT_NAME"
}

require_running_stack() {
  if ! stack_is_running; then
    die "The $WPU_MODE stack isn't running. Start it with 'dev/run up $WPU_MODE'."
  fi
}

# Creates the dev CA for `test` mode (kept across runs; removed by `down --volumes`).
ensure_dev_ca() {
  compose_run ca >/dev/null
}
